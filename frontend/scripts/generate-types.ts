/**
 * Generate TypeScript Types from OpenAPI Schema
 * 
 * Per Section 8.13: If used, generates TypeScript types FROM the backend's live
 * OpenAPI schema — authoritative over any manually-written type for the endpoints
 * it covers; reconcile manually-written types against its output, not the reverse.
 * 
 * This script connects to the running dashboard_api instance, fetches the OpenAPI
 * schema from /docs (Swagger UI), and generates TypeScript types that match the
 * backend's current API contract.
 * 
 * Usage:
 *   npm run generate-types
 *   node scripts/generate-types.ts
 * 
 * Requirements:
 *   - dashboard_api must be running and accessible via NEXT_PUBLIC_API_BASE_URL
 *   - OpenAPI schema must be available at {API_BASE_URL}/docs or {API_BASE_URL}/openapi.json
 */

import fs from 'fs';
import path from 'path';

// Configuration
const API_BASE_URL = process.env.NEXT_PUBLIC_API_BASE_URL || 'http://localhost:8001';
const OUTPUT_DIR = path.join(process.cwd(), '..', 'src', 'types', 'generated');
const OPENAPI_ENDPOINTS = [
  '/docs', // Swagger UI JSON endpoint
  '/openapi.json',
  '/api/v1/docs', // Alternative path
];

interface OpenAPISchema {
  openapi: string;
  info: {
    title: string;
    version: string;
  };
  paths: Record<string, any>;
  components: {
    schemas?: Record<string, any>;
    responses?: Record<string, any>;
    parameters?: Record<string, any>;
  };
}

/**
 * Fetch OpenAPI schema from the running backend
 */
async function fetchOpenAPISchema(): Promise<OpenAPISchema> {
  for (const endpoint of OPENAPI_ENDPOINTS) {
    try {
      const response = await fetch(`${API_BASE_URL}${endpoint}`);
      if (response.ok) {
        const schema = await response.json() as OpenAPISchema;
        console.log(`✓ Successfully fetched OpenAPI schema from ${endpoint}`);
        return schema;
      }
    } catch (error) {
      console.log(`✗ Failed to fetch from ${endpoint}:`, error instanceof Error ? error.message : String(error));
    }
  }

  throw new Error(
    `Unable to fetch OpenAPI schema from ${API_BASE_URL}. ` +
    'Ensure dashboard_api is running and accessible.'
  );
}

/**
 * Generate TypeScript type from OpenAPI schema
 */
function generateTypeScript(schema: OpenAPISchema): string {
  const lines: string[] = [];

  // Header
  lines.push('/**');
  lines.push(' * Auto-generated TypeScript types from OpenAPI schema');
  lines.push(` * Generated at: ${new Date().toISOString()}`);
  lines.push(` * API Version: ${schema.info.version}`);
  lines.push(` * OpenAPI Version: ${schema.openapi}`);
  lines.push(' * ');
  lines.push(' * DO NOT EDIT THIS FILE MANUALLY.');
  lines.push(' * Changes will be overwritten when running: npm run generate-types');
  lines.push(' * ');
  lines.push(' * Reconcile manually-written types against this output, not the reverse.');
  lines.push(' */');
  lines.push('');
  lines.push('/* eslint-disable */');
  lines.push('');

  // Generate schemas
  if (schema.components?.schemas) {
    lines.push('// ===== SCHEMA TYPES =====');
    lines.push('');

    for (const [name, schemaDef] of Object.entries(schema.components.schemas)) {
      lines.push(generateSchemaType(name, schemaDef));
      lines.push('');
    }
  }

  // Generate request/response types from paths
  if (schema.paths) {
    lines.push('// ===== ENDPOINT TYPES =====');
    lines.push('');

    for (const [path, pathDef] of Object.entries(schema.paths)) {
      for (const [method, operationDef] of Object.entries(pathDef)) {
        if (['get', 'post', 'put', 'patch', 'delete'].includes(method)) {
          lines.push(generateEndpointType(path, method, operationDef));
          lines.push('');
        }
      }
    }
  }

  return lines.join('\n');
}

/**
 * Generate TypeScript type for a schema
 */
function generateSchemaType(name: string, schemaDef: any): string {
  const typeName = toPascalCase(name);
  const lines: string[] = [];

  lines.push(`export interface ${typeName} {`);

  if (schemaDef.properties) {
    for (const [propName, propDef] of Object.entries(schemaDef.properties)) {
      const isRequired = schemaDef.required?.includes(propName);
      const tsType = openapiTypeToTypeScript(propDef);
      const optional = isRequired ? '' : '?';
      lines.push(`  ${propName}${optional}: ${tsType};`);
    }
  }

  if (schemaDef.allOf) {
    lines.push(`  // allOf: ${schemaDef.allOf.map((s: any) => s.$ref || s.type).join(', ')}`);
  }

  if (schemaDef.anyOf) {
    lines.push(`  // anyOf: ${schemaDef.anyOf.map((s: any) => s.$ref || s.type).join(', ')}`);
  }

  if (schemaDef.description) {
    lines.push(`  /** ${schemaDef.description} */`);
  }

  lines.push('}');

  return lines.join('\n');
}

/**
 * Generate TypeScript type for an endpoint
 */
function generateEndpointType(path: string, method: string, operationDef: any): string {
  const operationId = operationDef.operationId || `${method}_${path.replace(/[^a-zA-Z0-9]/g, '_')}`;
  const typeName = toPascalCase(operationId);
  const lines: string[] = [];

  lines.push(`// ${method.toUpperCase()} ${path}`);
  if (operationDef.summary) {
    lines.push(`// ${operationDef.summary}`);
  }

  // Request type
  if (operationDef.requestBody) {
    const content = operationDef.requestBody.content?.['application/json'];
    if (content?.schema) {
      lines.push(`export interface ${typeName}Request {`);
      lines.push(generateSchemaBody(content.schema, '  '));
      lines.push('}');
      lines.push('');
    }
  }

  // Response type
  if (operationDef.responses) {
    const successResponse = operationDef.responses['200'] || operationDef.responses['201'];
    if (successResponse?.content?.['application/json']?.schema) {
      lines.push(`export interface ${typeName}Response {`);
      lines.push(generateSchemaBody(successResponse.content['application/json'].schema, '  '));
      lines.push('}');
    }
  }

  return lines.join('\n');
}

/**
 * Generate schema body (properties)
 */
function generateSchemaBody(schema: any, indent: string): string {
  const lines: string[] = [];

  if (schema.$ref) {
    const refName = schema.$ref.split('/').pop();
    lines.push(`${indent}${toPascalCase(refName)};`);
    return lines.join('\n');
  }

  if (schema.type === 'object' && schema.properties) {
    for (const [propName, propDef] of Object.entries(schema.properties)) {
      const isRequired = schema.required?.includes(propName);
      const tsType = openapiTypeToTypeScript(propDef);
      const optional = isRequired ? '' : '?';
      lines.push(`${indent}${propName}${optional}: ${tsType};`);
    }
  } else if (schema.type === 'array' && schema.items) {
    const itemType = openapiTypeToTypeScript(schema.items);
    lines.push(`${indent}${itemType}[];`);
  } else {
    lines.push(`${indent}${openapiTypeToTypeScript(schema)};`);
  }

  return lines.join('\n');
}

/**
 * Convert OpenAPI type to TypeScript type
 */
function openapiTypeToTypeScript(schema: any): string {
  if (schema.$ref) {
    const refName = schema.$ref.split('/').pop();
    return toPascalCase(refName);
  }

  const type = schema.type || 'any';
  const format = schema.format;

  switch (type) {
    case 'string':
      if (format === 'date-time' || format === 'date') return 'string';
      if (format === 'email') return 'string';
      if (format === 'uuid') return 'string';
      if (format === 'uri') return 'string';
      if (format === 'binary') return 'Blob';
      return 'string';
    case 'number':
    case 'integer':
      if (format === 'int64') return 'number';
      if (format === 'int32') return 'number';
      if (format === 'float') return 'number';
      if (format === 'double') return 'number';
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      if (schema.items) {
        const itemType = openapiTypeToTypeScript(schema.items);
        return `${itemType}[]`;
      }
      return 'any[]';
    case 'object':
      if (schema.properties) {
        return 'Record<string, any>';
      }
      return 'Record<string, any>';
    default:
      return 'any';
  }
}

/**
 * Convert string to PascalCase
 */
function toPascalCase(str: string): string {
  return str
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
    .replace(/\s+/g, '');
}

/**
 * Ensure output directory exists
 */
function ensureOutputDir(): void {
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    console.log(`✓ Created output directory: ${OUTPUT_DIR}`);
  }
}

/**
 * Write generated types to file
 */
function writeTypesFile(content: string): void {
  const outputPath = path.join(OUTPUT_DIR, 'openapi.types.ts');
  fs.writeFileSync(outputPath, content, 'utf-8');
  console.log(`✓ Generated types written to: ${outputPath}`);
}

/**
 * Main execution
 */
async function main(): Promise<void> {
  console.log('='.repeat(60));
  console.log('TypeScript Type Generator from OpenAPI Schema');
  console.log('='.repeat(60));
  console.log(`API Base URL: ${API_BASE_URL}`);
  console.log(`Output Directory: ${OUTPUT_DIR}`);
  console.log('');

  try {
    ensureOutputDir();
    const schema = await fetchOpenAPISchema();
    const typescript = generateTypeScript(schema);
    writeTypesFile(typescript);

    console.log('');
    console.log('✓ Type generation completed successfully!');
    console.log('');
    console.log('Next steps:');
    console.log('1. Review the generated types in src/types/generated/openapi.types.ts');
    console.log('2. Reconcile manually-written types against the generated output');
    console.log('3. Update type imports to use the generated types where appropriate');
  } catch (error) {
    console.error('');
    console.error('✗ Type generation failed:', error instanceof Error ? error.message : String(error));
    console.error('');
    console.error('Troubleshooting:');
    console.error('- Ensure dashboard_api is running');
    console.error('- Check that NEXT_PUBLIC_API_BASE_URL is correctly set');
    console.error('- Verify the OpenAPI schema is accessible');
    process.exit(1);
  }
}

// Run if executed directly
if (require.main === module) {
  main();
}

export { main as generateTypes };
